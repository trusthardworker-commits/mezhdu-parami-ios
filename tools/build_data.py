groups = []

def group(name, page, rows, through="2026-12-29", warning=None):
    lessons = []
    for raw in rows.strip().splitlines():
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        fields = [v.strip() for v in raw.split("|")]
        day, slot, week, title = fields[0].split(" ", 3)
        item = dict(id=f"{name}-{len(lessons)+1}", weekday=int(day), period=int(slot),
                    week={"u":"upper", "l":"lower", "b":"both"}[week],
                    title=title, details=fields[1] if len(fields)>1 else "")
        if len(fields)>2:
            for rule in fields[2].split(";"):
                key, value = rule.strip().split(":", 1)
                item[{"from":"startsOn","until":"endsOn","only":"onlyDates","except":"excludedDates"}[key]] = value.split(",") if key in ("only","except") else value
        lessons.append(item)
    groups.append(dict(id=name, sourcePage=page, validFrom="2026-11-09", validThrough=through,
                       warning=warning, lessons=lessons))

